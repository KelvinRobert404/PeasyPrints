import type { CampusAudience, GenderPref, ListingPlace } from '@/types/campus';
import type { MarketCategory, MarketDetails, MarketListingDoc, MarketStatus, PriceTerms } from '@/types/market';
import { formatCampusSerial } from '../policy.ts';
import { AVAILABILITY_DAYS, RESERVE_HOURS } from '../constants.ts';
import { KJU, KJU_AIRPORT, KJU_MAIN, displayNameOf, fixtureTime, landmarkPlace, type FixtureCampusId, type FixtureDoc } from './core.ts';

interface MarketSpec {
  id: string;
  author: string;
  campusId?: FixtureCampusId;
  audience?: CampusAudience;
  category: MarketCategory;
  status?: MarketStatus;
  title: string;
  description: string;
  price: number | null;
  priceTerms: PriceTerms;
  place: ListingPlace | null;
  genderPref?: GenderPref;
  details: MarketDetails;
  /** Days since it was posted. */
  ageDays: number;
  /** Days since the seller last said it is still available. */
  confirmedDaysAgo?: number;
  /** Price before the drop, and days since the drop. */
  drop?: { from: number; daysAgo: number };
  /** Who holds the reserve, and hours left on it. */
  reserve?: { by: string; hoursLeft: number };
  /** Days from now until it stops showing, when it has a natural end. */
  endsInDays?: number;
}

function build(now: Date, spec: MarketSpec, index: number): FixtureDoc<MarketListingDoc> {
  const audience = spec.audience ?? 'campus';
  const sinceDays = spec.confirmedDaysAgo ?? spec.ageDays;
  const availabilityDays = Math.min(AVAILABILITY_DAYS - sinceDays, spec.endsInDays ?? Number.POSITIVE_INFINITY);
  const touchedDaysAgo = Math.min(spec.ageDays, spec.confirmedDaysAgo ?? spec.ageDays, spec.drop?.daysAgo ?? spec.ageDays);
  return {
    id: spec.id,
    data: {
      authorId: spec.author,
      serial: formatCampusSerial(KJU.collegeCode, 'M', index + 1),
      collegeId: KJU.collegeId,
      collegeCode: KJU.collegeCode,
      campusId: spec.campusId ?? KJU_MAIN,
      audience,
      kind: spec.details.kind,
      category: spec.category,
      status: spec.status ?? (spec.reserve ? 'reserved' : 'active'),
      title: spec.title,
      description: spec.description,
      price: spec.price,
      priceTerms: spec.priceTerms,
      previousPrice: spec.drop?.from ?? null,
      priceDroppedAt: spec.drop ? fixtureTime(now, -spec.drop.daysAgo) : null,
      images: [],
      place: spec.place,
      genderPref: spec.genderPref ?? (audience === 'girls' ? 'girls' : 'anyone'),
      details: spec.details,
      sellerDisplayName: displayNameOf(spec.author),
      promotionEligible: audience === 'campus',
      reservedBy: spec.reserve?.by ?? null,
      reservedUntil: spec.reserve ? fixtureTime(now, spec.reserve.hoursLeft / 24) : null,
      confirmedAt: spec.confirmedDaysAgo === undefined ? null : fixtureTime(now, -spec.confirmedDaysAgo),
      createdAt: fixtureTime(now, -spec.ageDays),
      updatedAt: fixtureTime(now, -touchedDaysAgo),
      availabilityExpiresAt: fixtureTime(now, availabilityDays),
    },
  };
}

